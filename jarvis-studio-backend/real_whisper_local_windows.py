"""Diagnostic of REAL faster-whisper ONNX/CT2 inference on generated SAPI clips.

Designed for ephemeral Windows CI. The WAVs are generated by System.Speech,
not human voices. A completed run is neither human wake nor offline FULL
installation certification. No score threshold is tuned here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import statistics
import sys
import time
import wave

import numpy as np


def read_wav_pcm16(path: Path) -> np.ndarray:
    try:
        with wave.open(str(path), "rb") as w:
            if (w.getnchannels(), w.getsampwidth(), w.getframerate(),
                    w.getcomptype()) != (1, 2, 16000, "NONE"):
                raise ValueError("unexpected_pcm16_format")
            frames = w.getnframes()
            if not 16000 <= frames <= 16000 * 10:
                raise ValueError("invalid_clip_duration")
            data = w.readframes(frames)
    except (OSError, wave.Error, EOFError) as exc:
        raise ValueError("invalid_wav") from exc
    pcm = np.frombuffer(data, dtype="<i2").copy()
    if pcm.size != frames:
        raise ValueError("truncated_wav")
    return pcm


def measure_cases(cases: list[dict], root: Path, *, detector_factory=None) -> dict:
    from wake_word.whisper_local_wake import LocalWhisperWake

    if not cases or len(cases) > 24:
        raise ValueError("invalid_number_of_cases")
    root = Path(root).resolve()
    observed = []
    seen = set()
    for item in cases:
        name = item.get("file")
        label = item.get("label")
        if (not isinstance(name, str) or not name.endswith(".wav")
                or Path(name).name != name or "/" in name or "\\" in name
                or label not in ("synthetic_positive", "synthetic_negative")
                or name in seen):
            raise ValueError("invalid_synthetic_case")
        seen.add(name)
        p = root / name
        if p.is_symlink() or not p.is_file():
            raise ValueError("missing_synthetic_audio")
        pcm = read_wav_pcm16(p)
        rms = float(np.sqrt(np.mean(pcm.astype(np.float64) ** 2)))
        if not math.isfinite(rms) or rms < 40:
            raise ValueError("silent_synthetic_case")
        detector = detector_factory() if detector_factory else LocalWhisperWake()
        # Pre-roll + end-of-utterance silence, same PCM16/80ms as JARVIS mic.
        samples = np.concatenate((
            np.zeros(1280 * 5, dtype=np.int16), pcm,
            np.zeros(1280 * 15, dtype=np.int16),
        ))
        pad = (-len(samples)) % 1280
        if pad:
            samples = np.pad(samples, (0, pad))
        started = time.perf_counter()
        events = []
        for i in range(0, len(samples), 1280):
            prediction = detector.predict(samples[i:i + 1280])
            if prediction not in (0.0, 1.0):
                raise ValueError("nonbinary_local_whisper_wake")
            if prediction == 1.0:
                events.append(i / 16000)
        observed.append({
            "label": label,
            "file_sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
            "triggered": bool(events),
            "event_count": len(events),
            "first_event_audio_time_s": events[0] if events else None,
            "wall_inference_ms": round((time.perf_counter() - started) * 1000),
            "audio_duration_s": round(pcm.size / 16000, 3),
        })
    positives = [x for x in observed if x["label"] == "synthetic_positive"]
    negatives = [x for x in observed if x["label"] == "synthetic_negative"]
    if not positives or not negatives:
        raise ValueError("both_synthetic_classes_required")
    return {
        "schema": "jarvis-local-whisper-wake-e2e-v1",
        "status": "MEASURED_SYNTHETIC_ONLY_NOT_CERTIFIED",
        "backend": "real_faster_whisper_cpu_int8" if detector_factory is None else "test_double",
        "synthetic_positive_count": len(positives),
        "synthetic_negative_count": len(negatives),
        "positive_triggered": sum(x["triggered"] for x in positives),
        "negative_false_activations": sum(x["triggered"] for x in negatives),
        "positive_recall_synthetic": sum(x["triggered"] for x in positives) / len(positives),
        "negative_false_activation_fraction_synthetic":
            sum(x["triggered"] for x in negatives) / len(negatives),
        "wall_ms_p50": int(statistics.median(x["wall_inference_ms"] for x in observed)),
        "wall_ms_max": max(x["wall_inference_ms"] for x in observed),
        "events": observed,
        "independent_human_positive_count": 0,
        "physical_microphone_certified": False,
        "offline_installer_certified": False,
        "human_false_reject_rate": None,
        "commercial_redistribution_certified": False,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument("--bundled-model", type=Path, required=True)
    ap.add_argument("--receipt", type=Path, required=True)
    args = ap.parse_args()
    if os.environ.get("GITHUB_ACTIONS") != "true" or os.environ.get("RUNNER_OS") != "Windows":
        raise SystemExit("Windows test must run in disposable GitHub CI")
    root = Path(os.environ["RUNNER_TEMP"]).resolve()
    if (args.manifest.resolve().parent != root or
            args.receipt.resolve().parent != root or
            args.bundled_model.resolve().parent != root):
        raise SystemExit("Paths must be directly within RUNNER_TEMP")
    report = {
        "status": "NOT_CERTIFIED", "physical_microphone_certified": False,
        "offline_installer_certified": False,
    }
    try:
        # Independent from caller's environment; never connect to remote STT.
        from wake_word.whisper_local_wake import LocalWhisperWake, load_local_whisper
        from full_offline_bundle_audit import REVIEWED_MODEL_SHA256
        w = args.bundled_model / "model.bin"
        expected = REVIEWED_MODEL_SHA256["preload-assets/whisper-base/model.bin"]
        if not w.is_file() or hashlib.sha256(w.read_bytes()).hexdigest() != expected:
            raise RuntimeError("pinned_whisper_weights_mismatch")
        cases = json.loads(args.manifest.read_text("utf-8"))
        if not isinstance(cases, list):
            raise ValueError("invalid_manifest")
        start = time.perf_counter()
        transcribe = load_local_whisper(bundled_model=str(args.bundled_model))
        load_ms = round((time.perf_counter() - start) * 1000)
        report = measure_cases(
            cases, root, detector_factory=lambda: LocalWhisperWake(transcribe=transcribe)
        )
        report["backend"] = "real_faster_whisper_cpu_int8"
        report["model_load_ms"] = load_ms
        report["whisper_weight_sha256"] = expected
        report["source_kind"] = "windows_sapi_synthetic_only"
    except Exception as exc:
        report["failure_type"] = type(exc).__name__
        report["status"] = "NOT_CERTIFIED"
    args.receipt.write_text(json.dumps(report, indent=2, sort_keys=True), encoding="utf-8")
    print("JARVIS_REAL_WHISPER_WAKE=" + json.dumps({
        key: report.get(key) for key in (
            "status", "failure_type", "positive_triggered", "negative_false_activations",
            "synthetic_positive_count", "synthetic_negative_count",
            "model_load_ms", "wall_ms_p50", "wall_ms_max",
        )}, sort_keys=True))
    return 0 if report["status"] == "MEASURED_SYNTHETIC_ONLY_NOT_CERTIFIED" else 1


if __name__ == "__main__":
    sys.exit(main())
