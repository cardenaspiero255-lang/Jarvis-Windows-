"""Approved, disposable Git repository experiment for JARVIS Windows.

Input to Ollama is fixed and public. Git runs only hard-coded local commands;
no cloned repository, network calls, git push, arbitrary commands or tests from
model-controlled source are allowed. No generated Python source is executed:
the regression evaluator is a tiny AST interpreter with no name resolution
outside the two permitted function parameters.
"""
from __future__ import annotations

import ast
import difflib
import hashlib
import json
import math
import os
from pathlib import Path
import re
import secrets
import subprocess
import tempfile
import time

from local_coding_pipeline import parse_proposal, CodingTaskError

FIXTURE_ROOT = Path(__file__).resolve().parent / "fixtures" / "controlled_repo"
_EXPECTED = {
    "src/totals.py": "def line_total(unit_price, quantity):\n    return unit_price - quantity\n",
    "src/discounts.py": ("def apply_discount(subtotal, percent):\n"
                         "    return subtotal + subtotal * percent / 100\n"),
}
_README = ("# JARVIS controlled programming repository\n\n"
           "This is a disposable, offline **test repository**, never a user project.\n"
           "Only `src/totals.py` and `src/discounts.py` may be edited by the demonstration.\n"
           "JARVIS creates a new local Git repository and a temporary branch from these trusted source files. No remote is configured, and no commits or pushes are generated by the coding agent.\n")
_TASKS = {
    "total": {
        "path": "src/totals.py", "function": "line_total",
        "vars": ("unit_price", "quantity"),
        "tests": ((0, 0, 0), (1, 1, 1), (3, 5, 15), (10, 0, 0),
                  (13, 2, 26), (7, 9, 63), (125, 4, 500)),
        "goal": "Return the extended total: unit_price multiplied by quantity.",
    },
    "discount": {
        "path": "src/discounts.py", "function": "apply_discount",
        "vars": ("subtotal", "percent"),
        "tests": ((100, 0, 100), (100, 50, 50), (200, 25, 150),
                  (40, 10, 36), (75, 100, 0), (0, 20, 0), (300, 33, 201)),
        "goal": "Subtract percent percent of subtotal. 0 percent leaves subtotal unchanged.",
    },
}
_COMMAND = re.compile(r"\b(corrige|arregla|repara|fix|repair)\b", re.IGNORECASE)
_DISCOUNT = re.compile(r"\b(descuento|discount)\b", re.IGNORECASE)
_TOTAL = re.compile(r"\b(total|totales|importe|line_total)\b", re.IGNORECASE)


def _fail(status, message, **fields):
    return {"ok": False, "status": status, "message": message,
            "tests_passed": 0, "tests_failed": 0, "published": False,
            "modified_user_repo": False, **fields}


def _task(command):
    if not isinstance(command, str) or len(command) > 200 or not _COMMAND.search(command):
        return None
    # Do not interpret arbitrary file/path or publishing requests as fixture work.
    if re.search(r"(?i)(?:\bgit\s+push\b|\bpush\b|\bpublica\b|\bpublish\b|"
                 r"\b(?:C:|/home/|\\.\\./)\b|"
                 r"\b(?:credenciales|credentials|secrets?)\b)", command):
        return None
    discount = bool(_DISCOUNT.search(command))
    total = bool(_TOTAL.search(command))
    if discount == total:
        return None
    return "discount" if discount else "total"


def _check_fixture():
    """Fail closed on changed fixtures; no user files enter the demonstration."""
    for name, expected in [*list(_EXPECTED.items()), ("README.md", _README)]:
        path = FIXTURE_ROOT.joinpath(*name.split("/"))
        if not path.is_file() or path.is_symlink():
            raise ValueError("Controlled repository fixture missing or symlinked")
        # Git checkout may convert trusted LF to CRLF on Windows. Normalize only
        # CRLF (never standalone CR), then compare the full pinned source bytes.
        actual = path.read_bytes()
        if b"\r" in actual.replace(b"\r\n", b""):
            raise ValueError("Unexpected carriage return in fixture")
        if actual.replace(b"\r\n", b"\n") != expected.encode("utf-8"):
            raise ValueError("Controlled repository fixture differs from pinned bytes")


def _expression(statement, names):
    if not isinstance(statement, str) or len(statement) > 110:
        raise CodingTaskError("Unexpected replacement length")
    try:
        module = ast.parse("def replacement(" + ", ".join(names) + "):\n    " + statement + "\n")
    except SyntaxError as exc:
        raise CodingTaskError("Invalid replacement AST") from exc
    if len(module.body) != 1 or not isinstance(module.body[0], ast.FunctionDef):
        raise CodingTaskError("Unexpected module")
    fn = module.body[0]
    if len(fn.body) != 1 or not isinstance(fn.body[0], ast.Return):
        raise CodingTaskError("Only one return statement is allowed")
    expr = fn.body[0].value
    count = [0]
    def validate(node, depth=0):
        count[0] += 1
        if depth > 7 or count[0] > 24:
            raise CodingTaskError("Expression too complex")
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
            if node.id not in names:
                raise CodingTaskError("Unknown variable")
            return
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            if not math.isfinite(node.value) or abs(node.value) > 100:
                raise CodingTaskError("Constant out of bounds")
            return
        if isinstance(node, ast.BinOp) and isinstance(
                node.op, (ast.Add, ast.Sub, ast.Mult, ast.Div)):
            validate(node.left, depth + 1)
            validate(node.right, depth + 1)
            return
        raise CodingTaskError("Disallowed operation in model-proposed code")
    validate(expr)
    return expr


def _evaluate(node, vars_):
    """No exec, eval, imports, function calls or attribute access."""
    if isinstance(node, ast.Name):
        return vars_[node.id]
    if isinstance(node, ast.Constant):
        return node.value
    a, b = _evaluate(node.left, vars_), _evaluate(node.right, vars_)
    if isinstance(node.op, ast.Add):
        return a + b
    if isinstance(node.op, ast.Sub):
        return a - b
    if isinstance(node.op, ast.Mult):
        return a * b
    if isinstance(node.op, ast.Div):
        return a / b
    raise CodingTaskError("Disallowed operation")


def _run_git(workspace, *args):
    """Only our own fixed Git operations; no model-controlled arguments.

    No network/remotes, hooks, global config, shell, executable scripts,
    or inherited Git config are permitted. Not a general sandbox for
    arbitrary repositories; safe only because the fixture is pinned.
    """
    env = os.environ.copy()
    env["GIT_CONFIG_NOSYSTEM"] = "1"
    env["GIT_CONFIG_GLOBAL"] = os.devnull
    env["GIT_TERMINAL_PROMPT"] = "0"
    env["GIT_LFS_SKIP_SMUDGE"] = "1"
    cmd = [
        "git",
        "-c", "core.hooksPath=" + str(workspace / ".disabled-hooks"),
        "-c", "core.autocrlf=false",
        "-c", "commit.gpgsign=false",
        *args,
    ]
    result = subprocess.run(cmd, cwd=str(workspace), env=env, check=True,
                            text=True, capture_output=True, timeout=20)
    return result.stdout.strip()


def repair_controlled_repository(command, proposer, *, workspace_root=None):
    """Approve externally, then repair one path on an unpushed local Git branch."""
    kind = _task(command)
    if kind is None:
        return _fail("unsupported", "Only controlled total or discount repairs are supported.")
    meta = _TASKS[kind]
    try:
        _check_fixture()
    except (OSError, ValueError):
        return _fail("fixture_invalid", "Pinned repository fixture was changed or missing.")

    original = _EXPECTED[meta["path"]]
    # Strict model context: only checked-in public fixture; no local private files.
    system = ("Fix ONE Python return expression in an offline teaching repository. "
              "Return strict JSON with one key only: replacement. "
              "Do not provide any commands, file paths, explanations or markdown. "
              "For example: {\"replacement\":\"return x + y\"}.")
    prompt = (f"Task: {meta['goal']}\n"
              f"File: {meta['path']}\n"
              f"Source:\n{original}"
              "Return ONLY JSON with a replacement return statement.")
    try:
        start = time.monotonic()
        proposal = proposer(system, prompt)
        latency_ms = max(0, round((time.monotonic() - start) * 1000))
    except (OSError, ValueError, RuntimeError, TimeoutError):
        return _fail("model_unavailable", "Ollama did not complete the model proposal.")
    try:
        replacement = parse_proposal(proposal)
        expr = _expression(replacement, meta["vars"])
    except CodingTaskError:
        return _fail("rejected", "Proposed change failed restricted AST and JSON validation.")

    passed = 0
    for left, right, expected in meta["tests"]:
        try:
            actual = _evaluate(expr, dict(zip(meta["vars"], (left, right))))
        except (ArithmeticError, ValueError, TypeError, OverflowError):
            return _fail("tests_failed", "A test raised an arithmetic exception.",
                         tests_failed=len(meta["tests"]) - passed, tests_passed=passed)
        if math.isfinite(actual) and math.isclose(
                actual, expected, rel_tol=1e-9, abs_tol=1e-9):
            passed += 1
    if passed != len(meta["tests"]):
        return _fail("tests_failed", "Arithmetic regressions rejected the patch.",
                     tests_failed=len(meta["tests"]) - passed, tests_passed=passed)

    # Write *only* after validation and tests. Only a new trusted temp tree.
    try:
        parent = None
        if workspace_root is not None:
            parent = Path(workspace_root).resolve(strict=True)
            if not parent.is_dir():
                raise OSError("Invalid workspace")
        workspace = Path(tempfile.mkdtemp(prefix="jarvis-git-demo-",
                            dir=str(parent) if parent else None))
        for path, contents in (*_EXPECTED.items(), ("README.md", _README)):
            target = workspace.joinpath(*path.split("/"))
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(contents.encode("utf-8"))
        _run_git(workspace, "init", "--initial-branch=main")
        _run_git(workspace, "add", "--", "README.md", "src/totals.py", "src/discounts.py")
        _run_git(workspace, "-c", "user.name=JARVIS Fixture",
                 "-c", "user.email=jarvis-fixture@localhost",
                 "commit", "-m", "Trusted offline fixture baseline")
        branch = "jarvis/demo-" + secrets.token_hex(6)
        _run_git(workspace, "switch", "-c", branch)
        source = original.splitlines(keepends=True)
        if len(source) != 2 or not source[1].startswith("    return "):
            raise ValueError("Pinned fixture structure invalid")
        fixed = source[0] + "    " + replacement.strip() + "\n"
        # The written code was structurally validated and tested via a pure AST interpreter.
        target = workspace.joinpath(*meta["path"].split("/"))
        target.write_bytes(fixed.encode("utf-8"))
        changed = _run_git(workspace, "diff", "--name-only").splitlines()
        if changed != [meta["path"]]:
            raise RuntimeError("Unexpected diff in controlled repository")
        diff = _run_git(workspace, "diff", "--", meta["path"])
        if not diff or _run_git(workspace, "remote"):
            raise RuntimeError("Missing patch or unexpected remote")
        base_sha = _run_git(workspace, "rev-parse", "main")
        if _run_git(workspace, "rev-parse", "HEAD") != base_sha:
            raise RuntimeError("Unexpected commit; generated fix must be uncommitted")
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError):
        return _fail("workspace_error", "Failed to create or verify an isolated Git branch.")
    return {
        "ok": True, "status": "verified_local_branch",
        "message": "Controlled Git branch created; bounded tests passed, no remote publish.",
        "workspace": str(workspace), "branch": branch,
        "tests_passed": passed, "tests_failed": 0,
        "modified_files": changed, "diff": diff,
        "source_sha256": hashlib.sha256(fixed.encode("utf-8")).hexdigest(),
        "baseline_commit": base_sha, "latency_ms": latency_ms,
        "published": False, "modified_user_repo": False,
        "model_source": "local_model_proposal",
    }
